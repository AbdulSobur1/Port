import type { Building, BuildingChunk, GraphPayload, Provenance, WorldData } from './types';

/** Small fetch helper that surfaces HTTP failures instead of hanging on bad JSON. */
/**
 * Bumped when the geo pipeline rewrites a shipped payload. Static files keep
 * stable names, so a browser or CDN that cached an older street layout would
 * otherwise keep showing it after a rebuild.
 */
export const DATA_REVISION = '4';

async function getJson<T>(url: string, signal?: AbortSignal, attempt = 0): Promise<T> {
  let res: Response;
  try {
    // Revalidate rather than force-cache: the world payloads are regenerated by
    // the geo pipeline under stable filenames, and a stale station list is
    // exactly the kind of drift this project cannot afford.
    res = await fetch(url, { signal, cache: 'no-cache' });
  } catch (error) {
    if (attempt < 2 && !signal?.aborted) {
      await new Promise((r) => setTimeout(r, 400 * (attempt + 1)));
      return getJson<T>(url, signal, attempt + 1);
    }
    throw new Error(`Could not load ${url}: ${(error as Error).message}`);
  }
  if (!res.ok) {
    if (attempt < 2 && res.status >= 500 && !signal?.aborted) {
      await new Promise((r) => setTimeout(r, 400 * (attempt + 1)));
      return getJson<T>(url, signal, attempt + 1);
    }
    throw new Error(`Could not load ${url} (HTTP ${res.status})`);
  }
  return (await res.json()) as T;
}

export type WorldBundle = { world: WorldData; graph: GraphPayload; provenance: Provenance };

let worldPromise: Promise<WorldBundle> | null = null;
const chunkCache = new Map<string, Promise<BuildingChunk>>();

/**
 * World + graph are loaded together: the map, scene and autopilot all need both.
 *
 * The request is shared and deliberately *not* bound to a caller's AbortSignal:
 * a React remount (or any consumer unmounting mid-load) would otherwise abort
 * the one cached promise and leave every later reader with
 * "signal is aborted without reason" instead of data. Retries are handled by
 * `getJson` itself, and a genuine failure clears the cache below.
 */
export function loadWorld(_signal?: AbortSignal): Promise<WorldBundle> {
  if (!worldPromise) {
    worldPromise = Promise.all([
      getJson<WorldData>(`/data/lagos-world.json?v=${DATA_REVISION}`),
      getJson<GraphPayload>(`/data/lagos-graph.json?v=${DATA_REVISION}`),
      getJson<Provenance>(`/data/lagos-provenance.json?v=${DATA_REVISION}`).catch(
        () =>
          ({
            generatedAt: '',
            source: { name: 'OpenStreetMap', url: '', snapshot: '', license: 'ODbL-1.0', attribution: '© OpenStreetMap contributors', sha256: '', bytes: 0 },
            bounds: { west: 0, south: 0, east: 0, north: 0 },
            crs: { source: '', world: '', scaleAtOrigin: 1, distortionNote: '' },
            counts: {},
            quality: {},
            outputs: {},
          }) as Provenance
      ),
    ])
      .then(([world, graph, provenance]) => ({ world, graph, provenance }))
      .catch((error) => {
        worldPromise = null; // allow a retry after a network hiccup
        throw error;
      });
  }
  return worldPromise;
}

export function buildingChunkUrl(row: number, col: number): string {
  return `/data/lagos-buildings-${row}${col}.json?v=${DATA_REVISION}`;
}

export function loadBuildingChunk(row: number, col: number): Promise<BuildingChunk> {
  const key = `${row}${col}`;
  let pending = chunkCache.get(key);
  if (!pending) {
    pending = getJson<BuildingChunk>(buildingChunkUrl(row, col)).catch((error) => {
      chunkCache.delete(key);
      throw error;
    });
    chunkCache.set(key, pending);
  }
  return pending;
}

/** Which building bundle covers a world position (clamped at the edges). */
export function chunkForWorld(x: number, z: number, meta: WorldData['meta']): { row: number; col: number } {
  const n = meta.chunks;
  const { minX, minZ } = meta.worldBounds;
  const col = Math.min(n - 1, Math.max(0, Math.floor(((x - minX) / meta.size.width) * n)));
  const row = Math.min(n - 1, Math.max(0, Math.floor(((z - minZ) / meta.size.depth) * n)));
  return { row, col };
}

/** 3×3 neighbourhood of chunks around a position (radius in chunks). */
export function chunksAround(x: number, z: number, meta: WorldData['meta'], radius = 1): { row: number; col: number }[] {
  const { row, col } = chunkForWorld(x, z, meta);
  const out: { row: number; col: number }[] = [];
  for (let r = row - radius; r <= row + radius; r++) {
    for (let c = col - radius; c <= col + radius; c++) {
      if (r >= 0 && c >= 0 && r < meta.chunks && c < meta.chunks) out.push({ row: r, col: c });
    }
  }
  return out;
}

export type { WorldData, GraphPayload, Provenance, Building, BuildingChunk };
